#!/usr/bin/env python3
"""
Instagram 单条入库（帖子 / Reel / 图文 / 多图）
- 依赖 gallery-dl（独立 venv，不污染系统）
- cookie 走 IG_COOKIE_FILE，兼容 Netscape cookies.txt 与 "sessionid=...; csrftoken=..." 单行
- 统一走 PROXY_URL（默认 http://127.0.0.1:2080）
- 文件落盘：MEDIA/Instagram/<YYYY-MM-DD>/<标题>/1.jpg|1.mp4 ...
返回 (rel, title, platform, author)
"""
import json
import os
import re
import shutil
import subprocess
import tempfile
import time
import urllib.parse

from config import MEDIA_ROOT, PROXY_URL
from utils import clean_title, sanitize_filename, gen_thumb_ffmpeg
from logger import log

MEDIA = MEDIA_ROOT
IG_COOKIE_FILE = os.environ.get(
    "IG_COOKIE_FILE", "/home/16675244747/.hermes/workspace/ig_cookie.txt"
)
IG_GALLERY_DL = os.environ.get(
    "IG_GALLERY_DL", "/home/16675244747/.hermes/workspace/ig-dl/.venv/bin/gallery-dl"
)
IG_PROXY = os.environ.get("IG_PROXY") or PROXY_URL or "http://127.0.0.1:2080"

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36")

MEDIA_EXT = (".jpg", ".jpeg", ".png", ".webp", ".gif", ".mp4", ".mov", ".m4v", ".webm")

NO_COOKIE_MSG = "需要 Instagram cookie（IG_COOKIE_FILE）"


class IGNoCookie(RuntimeError):
    """缺少/无效 cookie（永久性错误，worker 不该重试）"""


def _today():
    return time.strftime("%Y-%m-%d")


def normalize_ig_url(url):
    """去掉 igsh/share 追踪参数，统一 /p/ /reel/ /tv/ 形态"""
    u = (url or "").strip()
    u = u.replace("https://instagram.com", "https://www.instagram.com")
    u = u.replace("http://", "https://") if u.startswith("http://") else u
    p = urllib.parse.urlsplit(u)
    path = re.sub(r"/(embed|embed/captioned)/?$", "/", p.path)
    if not path.endswith("/"):
        path += "/"
    return urllib.parse.urlunsplit(("https", "www.instagram.com", path, "", ""))


def _parse_cookie_file(path):
    """读取 cookie 文件，返回 Netscape 行列表；单行 cookie 自动转换。
    没有有效内容返回 None。"""
    try:
        raw = open(path, "r", encoding="utf-8", errors="ignore").read()
    except Exception:
        return None
    raw = raw.strip()
    if not raw:
        return None
    lines = []
    for ln in raw.splitlines():
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        if "\t" in ln and len(ln.split("\t")) >= 7:
            lines.append(ln)
    if lines:
        return lines
    # 单行 "sessionid=xxx; csrftoken=yyy"
    pairs = []
    for part in re.split(r";\s*", raw.replace("\n", ";")):
        if "=" in part:
            k, v = part.split("=", 1)
            k, v = k.strip(), v.strip().strip('"')
            if k and v:
                pairs.append((k, v))
    if not any(k == "sessionid" for k, _ in pairs):
        return None
    exp = int(time.time()) + 365 * 86400
    out = []
    for k, v in pairs:
        out.append("\t".join([".instagram.com", "TRUE", "/", "TRUE", str(exp), k, v]))
    return out


def cookie_file_or_none():
    """返回可直接交给 gallery-dl 的 Netscape cookie 文件路径；无 cookie 返回 None"""
    src = IG_COOKIE_FILE
    if not os.path.isfile(src):
        return None
    lines = _parse_cookie_file(src)
    if not lines:
        return None
    # 已是 Netscape 格式直接复用
    try:
        head = open(src, "r", encoding="utf-8", errors="ignore").read(200)
    except Exception:
        head = ""
    if "\t" in head and "sessionid" in head:
        return src
    tmpdir = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".tmp", "ig_cookie")
    os.makedirs(tmpdir, exist_ok=True)
    dst = os.path.join(tmpdir, "cookies.txt")
    header = ["# Netscape HTTP Cookie File", "# generated by ig_downloader", ""]
    with open(dst, "w", encoding="utf-8") as f:
        f.write("\n".join(header + lines) + "\n")
    os.chmod(dst, 0o600)
    return dst


def _run_gallery_dl(url, dest, cookie_file):
    """调 gallery-dl 下载到 dest，返回 (ok, 输出文本)"""
    if not os.path.isfile(IG_GALLERY_DL):
        raise RuntimeError(f"gallery-dl 未安装: {IG_GALLERY_DL}")
    cmd = [
        IG_GALLERY_DL,
        "--proxy", IG_PROXY,
        "--user-agent", UA,
        "--no-mtime",
        "--write-metadata",
        "-D", dest,
    ]
    if cookie_file:
        cmd[3:3] = ["--cookies", cookie_file]
    cmd.append(url)
    log.info(f"gallery-dl 开始: {url}")
    try:
        r = subprocess.run(cmd, capture_output=True, timeout=150)
    except subprocess.TimeoutExpired:
        raise RuntimeError("Instagram 下载超时（多为 429 限流，建议配置 cookie 或换代理出口）")
    out = (r.stdout or b"").decode("utf-8", "ignore") + (r.stderr or b"").decode("utf-8", "ignore")
    files = [f for f in os.listdir(dest) if f.lower().endswith(MEDIA_EXT)]
    return (r.returncode == 0 and bool(files)), out


def _read_meta(dest):
    """从 gallery-dl 写的 *.json 读 caption / username"""
    title, author = "", ""
    try:
        for fn in os.listdir(dest):
            if not fn.lower().endswith(".json"):
                continue
            try:
                d = json.load(open(os.path.join(dest, fn), encoding="utf-8", errors="ignore"))
            except Exception:
                continue
            if not isinstance(d, dict):
                continue
            title = title or (d.get("description") or d.get("caption") or "")
            author = author or (d.get("username") or d.get("fullname") or "")
            if title and author:
                break
    except Exception:
        pass
    return title.strip(), author.strip()


def _rename_sequential(dest):
    """1.jpg / 1.mp4 / 2.jpg ... 按序号命名，并清掉 json/临时文件"""
    names = sorted(
        [f for f in os.listdir(dest) if f.lower().endswith(MEDIA_EXT)],
        key=lambda x: [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", x)],
    )
    for i, fn in enumerate(names, 1):
        ext = os.path.splitext(fn)[1].lower()
        if ext == ".jpeg":
            ext = ".jpg"
        src = os.path.join(dest, fn)
        dst = os.path.join(dest, f"{i}{ext}")
        if os.path.abspath(src) != os.path.abspath(dst):
            os.replace(src, dst)
    for fn in os.listdir(dest):
        if fn.lower().endswith((".json", ".txt", ".part")):
            try:
                os.remove(os.path.join(dest, fn))
            except Exception:
                pass
    return [f"{i}{os.path.splitext(f)[1].lower()}" for i, f in enumerate(names, 1)]


def _make_thumb(dest, title):
    """缩略图：视频抽帧 / 图片缩放，宽 720"""
    files = sorted([f for f in os.listdir(dest) if f.lower().endswith(MEDIA_EXT)])
    if not files:
        return
    videos = [f for f in files if f.lower().endswith((".mp4", ".mov", ".m4v", ".webm"))]
    src = os.path.join(dest, videos[0] if videos else files[0])
    thumb = os.path.join(dest, "_thumb.jpg")
    try:
        cmd = ["ffmpeg", "-y"]
        if videos:
            cmd += ["-ss", "0.5"]
        cmd += ["-i", src, "-frames:v", "1", "-vf", "scale=720:-2", "-q:v", "4", thumb]
        subprocess.run(cmd, capture_output=True, timeout=60)
        if os.path.isfile(thumb) and os.path.getsize(thumb) > 3000:
            return
    except Exception:
        pass
    try:
        gen_thumb_ffmpeg(src, thumb, is_image=not videos)
    except Exception as e:
        log.warning(f"IG 缩略图生成失败: {e}")


def download_instagram(url):
    """Instagram 单条（帖子/Reel/图文）下载 → (rel, title, platform, author)"""
    cookie_file = cookie_file_or_none()
    if not cookie_file and os.environ.get("IG_ALLOW_NO_COOKIE") != "1":
        raise IGNoCookie(NO_COOKIE_MSG)

    real = normalize_ig_url(url)
    tmp = tempfile.mkdtemp(prefix="ig_", dir=os.path.join(MEDIA, ".ig_tmp") if os.path.isdir(os.path.join(MEDIA, ".ig_tmp")) else None)
    try:
        ok, out = _run_gallery_dl(real, tmp, cookie_file)
        if not ok:
            tail = " ".join([ln for ln in out.splitlines() if ln.strip()][-4:])[:180]
            low = out.lower()
            if "429" in low or "too many requests" in low:
                raise RuntimeError(f"Instagram 限流(429)，请稍后重试或用 cookie: {tail}")
            if "login" in low or "401" in low or "403" in low:
                raise RuntimeError(f"Instagram 需要登录/cookie 已失效（{NO_COOKIE_MSG}）: {tail}")
            if "not found" in low or "404" in low:
                raise RuntimeError(f"Instagram 帖子不存在或已删除/私密: {tail}")
            raise RuntimeError(f"Instagram 下载失败: {tail}")

        raw_title, author = _read_meta(tmp)
        title = clean_title(raw_title) or "Instagram"
        title = sanitize_filename(title) or "Instagram"
        files = _rename_sequential(tmp)
        if not files:
            raise RuntimeError("Instagram 未取到任何图片/视频（可能需 cookie）")

        dest = os.path.join(MEDIA, "Instagram", _today(), title)
        if os.path.isdir(dest):
            title = f"{title}_{int(time.time()) % 100000}"
            dest = os.path.join(MEDIA, "Instagram", _today(), title)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        shutil.move(tmp, dest)
        _make_thumb(dest, title)
        log.info(f"IG 完成: {title} ({len(files)} 个媒体, 作者 {author or '?'})")
        return os.path.join("Instagram", _today(), title), title, "Instagram", author
    finally:
        if os.path.isdir(tmp):
            shutil.rmtree(tmp, ignore_errors=True)
